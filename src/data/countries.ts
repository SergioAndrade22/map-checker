// Quick index maps
const byNumericId = new Map<string, CountryMetadata>();
const byName = new Map<string, CountryMetadata>();
const byAlpha3 = new Map<string, CountryMetadata>();

for (const country of COUNTRIES_DATA) {
  const normId = country.id.padStart(3, '0');
  byNumericId.set(normId, country);
  byNumericId.set(String(parseInt(normId, 10)), country);
  byName.set(country.name.toLowerCase(), country);
  byAlpha3.set(country.alpha3.toUpperCase(), country);
}

/**
 * Find country metadata by ID, code, or name, with a safe fallback
 */
export function getCountryMeta(idOrName: string | number | undefined, fallbackName?: string): CountryMetadata {
  if (idOrName === undefined || idOrName === null) {
    return {
      id: "unknown",
      name: fallbackName || "Unknown Country",
      alpha2: "??",
      alpha3: "UNK",
      flag: "🌐",
      areaKm2: 0,
      population: 0,
      continent: "Global"
    };
  }

  const str = String(idOrName).trim();
  const padded = str.padStart(3, '0');

  if (byNumericId.has(padded)) return byNumericId.get(padded)!;
  if (byNumericId.has(str)) return byNumericId.get(str)!;

  const lower = (fallbackName || str).toLowerCase();
  if (byName.has(lower)) return byName.get(lower)!;
  if (byAlpha3.has(str.toUpperCase())) return byAlpha3.get(str.toUpperCase())!;

  // Fallback metadata generated gracefully
  const cleanName = fallbackName || str;
  return {
    id: padded,
    name: cleanName,
    alpha2: cleanName.slice(0, 2).toUpperCase(),
    alpha3: cleanName.slice(0, 3).toUpperCase(),
    flag: "🌐",
    areaKm2: 100000,
    population: 10000000,
    continent: "Global"
  };
}
